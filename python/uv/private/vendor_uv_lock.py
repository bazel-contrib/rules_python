"""Vendor a `uv.lock` file as a JSON string constant in a `.bzl` file.

The vendored data is a subset of the `uv.lock` file, which has only the fields
that are needed for selecting the distributions. It is rendered with one
package and one distribution per line, so that the diffs are small and easy to
review.

Usage:
    vendor_uv_lock.py build --src uv.lock --out out.bzl ...
    vendor_uv_lock.py update --src pkg/uv.lock --out pkg/uv_lock.bzl ...
"""

import argparse
import json
import os
import pathlib
import subprocess
import sys

try:
    import tomllib
except ImportError:  # Python < 3.11
    import tomli as tomllib  # type: ignore[no-redef]

# The keys that are kept for each package, dependency and distribution.
_PACKAGE_KEYS = ("name", "version", "source", "resolution-markers", "provides-extras")
_DEPENDENCY_KEYS = ("extra", "marker", "name", "source", "version")
_DEPENDENCY_TABLES = ("optional-dependencies", "dev-dependencies")
_DISTRIBUTION_KEYS = ("hash", "url")

_HEADER = '''\
"""The vendored `{src}` file.

@generated by `bazel run {update_target}`. DO NOT EDIT.
"""

'''


def _pick(d: dict, keys: tuple) -> dict:
    return {k: d[k] for k in keys if k in d}


def trim(lock: dict) -> list:
    """Return the packages of the lock file with only the needed fields."""
    packages = []
    for pkg in lock.get("package", []):
        out = _pick(pkg, _PACKAGE_KEYS)
        if pkg.get("dependencies"):
            out["dependencies"] = [
                _pick(d, _DEPENDENCY_KEYS) for d in pkg["dependencies"]
            ]
        for table in _DEPENDENCY_TABLES:
            if pkg.get(table):
                out[table] = {
                    group: [_pick(d, _DEPENDENCY_KEYS) for d in deps]
                    for group, deps in pkg[table].items()
                }

        # Only the requirements with extras are used.
        requires_dist = [
            _pick(rd, ("extras", "name"))
            for rd in pkg.get("metadata", {}).get("requires-dist", [])
            if rd.get("extras")
        ]
        if requires_dist:
            out["metadata"] = {"requires-dist": requires_dist}
        if pkg.get("sdist"):
            out["sdist"] = _pick(pkg["sdist"], _DISTRIBUTION_KEYS)
        if pkg.get("wheels"):
            out["wheels"] = [_pick(w, _DISTRIBUTION_KEYS) for w in pkg["wheels"]]
        packages.append(out)
    return packages


def render(packages: list, *, constant: str, src: str, update_target: str) -> str:
    """Render the packages as a JSON string constant.

    Each package is on its own line and each wheel is on its own line, so that
    updating a package only changes the lines of that package.
    """
    lines = []
    for i, pkg in enumerate(packages):
        sep = "," if i + 1 < len(packages) else ""
        wheels = pkg.get("wheels", [])
        head = {k: v for k, v in pkg.items() if k != "wheels"}
        head_json = json.dumps(head, sort_keys=True)
        if not wheels:
            lines.append(head_json + sep)
            continue

        lines.append(head_json[:-1] + ', "wheels": [')
        for j, wheel in enumerate(wheels):
            wheel_sep = "," if j + 1 < len(wheels) else ""
            lines.append("    " + json.dumps(wheel, sort_keys=True) + wheel_sep)
        lines.append("]}" + sep)

    body = "\n".join(lines)
    return (
        _HEADER.format(src=src, update_target=update_target)
        + f'{constant} = r"""{{"package": [\n{body}\n]}}\n"""\n'
    )


def vendor(src: pathlib.Path, out: pathlib.Path, args: argparse.Namespace) -> None:
    lock = tomllib.loads(src.read_text())
    out.write_text(
        render(
            trim(lock),
            constant=args.constant,
            src=args.src_label,
            update_target=args.update_target,
        )
    )


def _find_runfile(path: str) -> str:
    from python.runfiles import runfiles

    r = runfiles.CreateOrRaise()
    found = r.Rlocation(path)
    if not found:
        raise FileNotFoundError(path)
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=["build", "update"])
    parser.add_argument("--src", required=True, help="The uv.lock file.")
    parser.add_argument("--out", required=True, help="The .bzl file to write.")
    parser.add_argument("--constant", required=True)
    parser.add_argument("--src_label", required=True)
    parser.add_argument("--update_target", required=True)
    parser.add_argument(
        "--lock_runner",
        help="The runfiles path of the lock target to run before vendoring.",
    )
    args, lock_args = parser.parse_known_args()

    if args.mode == "build":
        vendor(pathlib.Path(args.src), pathlib.Path(args.out), args)
        return 0

    if "BUILD_WORKSPACE_DIRECTORY" not in os.environ:
        raise RuntimeError("The update mode must be run via `bazel run`")

    if args.lock_runner:
        # Update the uv.lock first, so that the vendored file is created from
        # the updated lock file.
        subprocess.run(
            [_find_runfile(args.lock_runner)] + lock_args,
            check=True,
        )

    workspace = pathlib.Path(os.environ["BUILD_WORKSPACE_DIRECTORY"])
    out = workspace / args.out
    vendor(workspace / args.src, out, args)
    print(f"OK: updated {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
